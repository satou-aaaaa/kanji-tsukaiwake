  function lvl(set, me, sents) {
    return (R, lv) => {
      const si = ri(R, 0, sents.length - 1), p = parse(sents[si]), others = set[2].filter((x) => x[0] !== me[0] && !p.ng.includes(x[1]));
      const use = others.length <= 2 ? others : pickN(R, others, lv === 2 ? 3 : 2);
      const ans = me[1] + p.okuri, opts = shuffle(R, [ans, ...use.map((x) => x[1] + p.okuri)]);
      const q = `「${p.yomi || set[1]}」：${p.pre}＿＿${p.post}　どの漢字？`;
      return { type: "act", q, opts, ans, rev: false, full: p.pre + ans + p.post, v: `${si}:${use.map((x) => x[0]).join(".")}` };
    };
  }
