  const parse = (s) => { const m = /^(.*)\[(.)([^\]|]*)(?:\|([^\]|-][^\]|]*))?(?:\|-([^\]]*))?\](.*)$/.exec(s); return { pre: m[1], kanji: m[2], okuri: m[3], yomi: m[4] || "", ng: m[5] || "", post: m[6] }; };

